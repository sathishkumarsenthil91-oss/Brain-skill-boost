export function createAuthenticatedUserProfile(name?: string, email?: string, additional?: Partial<UserProfile>): UserProfile {
  const cleanEmail = (email || '').trim();
  const rawName = (name || '').trim();
  
  // Format fallback display name nicely if only email is provided
  let displayName = rawName;
  if (!displayName && cleanEmail) {
    const handle = cleanEmail.split('@')[0];
    displayName = handle
      .split(/[._-]/)
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join(' ');
  }
  if (!displayName) {
    displayName = 'Student Developer';
  }

  return {
    name: displayName,
    avatarUrl: additional?.avatarUrl || DEFAULT_USER_AVATAR,
    email: cleanEmail || '',
    phone: additional?.phone || '',
    bio: additional?.bio || '',
    college: additional?.college || '',
    degree: additional?.degree || '',
    gradYear: additional?.gradYear || '',
    gpa: additional?.gpa || '',
    location: additional?.location || '',
    targetRole: additional?.targetRole || 'Full Stack Developer',
    githubUrl: additional?.githubUrl || '',
    linkedinUrl: additional?.linkedinUrl || '',
    portfolioUrl: additional?.portfolioUrl || '',
    resumeFileName: additional?.resumeFileName || '',
    overallReadiness: additional?.overallReadiness ?? 0,
    matchedSkillsCount: additional?.matchedSkillsCount ?? 0,
    totalTargetSkills: additional?.totalTargetSkills ?? 0,
    learningProgress: additional?.learningProgress ?? 0,
    activeCoursesCount: additional?.activeCoursesCount ?? 0,
    opportunitiesCount: additional?.opportunitiesCount ?? 0,
    newMatchedCount: additional?.newMatchedCount ?? 0,
    completedAssignmentsCount: additional?.completedAssignmentsCount ?? 0,
    certificationsCount: additional?.certificationsCount ?? 0,
    earnedCertificates: additional?.earnedCertificates || [],
    projects: additional?.projects || [],
    internships: additional?.internships || [],
    achievements: additional?.achievements || [],
    learningRecords: additional?.learningRecords || [],
    isPrivateAccount: additional?.isPrivateAccount ?? false,
  };
}

